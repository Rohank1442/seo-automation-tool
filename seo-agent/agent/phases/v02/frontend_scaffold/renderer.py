"""Render project-independent HTML templates for scaffold pages."""

import json
from html import escape


def build_link_map(internal_linking: dict) -> dict:
    """Group internal links by their source page ID."""
    result = {}
    for link in internal_linking.get("links", []):
        source = link.get("source_page_id")
        target = link.get("target_url")
        if source and target:
            result.setdefault(source, []).append((target, link.get("anchor_text") or "Read more"))
    return result


def render_page(page: dict, all_pages: list, links_by_source: dict) -> str:
    """Render a crawlable HTML shell; v0.3 supplies the article body later."""
    title = page.get("title") or "Untitled page"
    canonical = page.get("canonical_url") or page.get("url", "/")
    description = page.get("meta_description") or f"Explore {title}."
    nav = "\n".join(
        f'<a href="{escape(item.get("url", "/"), quote=True)}">{escape(item.get("title") or "Page")}</a>'
        for item in all_pages if item.get("page_id") != page.get("page_id")
    )
    related = "\n".join(
        f'<li><a href="{escape(url, quote=True)}">{escape(anchor)}</a></li>'
        for url, anchor in links_by_source.get(page.get("page_id"), [])
    )
    related_section = f"<section><h2>Related pages</h2><ul>{related}</ul></section>" if related else ""
    keyword = page.get("primary_keyword")
    keyword_context = f'<p class="topic">Primary topic: {escape(keyword)}</p>' if keyword else ""
    schema = json.dumps({"@context": "https://schema.org", "@type": "WebPage", "name": title, "url": canonical}, ensure_ascii=False)
    return f'''<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>{escape(title)}</title><meta name="description" content="{escape(description, quote=True)}">
<meta name="robots" content="{escape(page.get("robots", "index, follow"), quote=True)}">
<link rel="canonical" href="{escape(canonical, quote=True)}">
<meta property="og:title" content="{escape(title, quote=True)}"><meta property="og:description" content="{escape(description, quote=True)}">
<script type="application/ld+json">{schema}</script>
<style>body{{font:16px/1.7 Arial,sans-serif;color:#222;margin:0}}header,footer{{padding:20px;background:#f5f5f5}}nav,main{{max-width:1000px;margin:auto;padding:20px}}nav{{display:flex;flex-wrap:wrap;gap:16px}}a{{color:#2457a7}}article{{max-width:850px;margin:40px auto}}h1{{line-height:1.2}}.intro{{color:#555;font-size:1.15rem}}</style></head>
<body><header><nav>{nav}</nav></header><main><article><h1>{escape(title)}</h1>
<p class="intro">This page is part of the {escape(page.get("cluster") or "site")} topic area.</p>{keyword_context}
<section><h2>Overview</h2><p>Detailed page content will be added during the content generation phase.</p></section>
{related_section}</article></main><footer>Generated by the SEO Automation Agent — v0.2</footer></body></html>'''
